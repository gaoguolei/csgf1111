-- ============================================================
-- 租金台账：安装信息快照
-- ============================================================
-- 背景：
--   租金详情、对账单 PDF、导出都以"这一期当时的数据"为准。
--   安装信息（房型、型号、块数、容量、档位单价）原来每次实时查农户，
--   农户改了安装信息后，已提交/已支付的期数详情会跟着变，历史对账单失真。
--
-- 处理：
--   台账生成/重新生成时把当时的安装信息整份存成 JSON，详情和 PDF 直接读它。
--   存量台账该列为空，接口会回落到实时查询，不影响历史数据展示。
-- ============================================================

ALTER TABLE `t_rent_ledger`
    ADD COLUMN `install_snapshot` longtext
        COMMENT '生成时的安装信息快照（房型、型号、块数、容量、档位单价），JSON'
        AFTER `total_capacity`;
